#!/usr/bin/env python3
"""Validate Lean/LaTeX coverage and check (or regenerate) the published ledger.

Run after `lake build`. Standalone checks use an exported statement inventory.
Pass --book PATH to compare the private manuscript and its tables as well.
--write updates generated artifacts; the default is read-only. Lean resolves declaration names and audits the
axioms of all project theorems before any artifact is accepted.
"""
import argparse
from collections import Counter
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
STATUS = {
    "complete": "complete",
    "partiallyComplete": "partial",
    "formalizableNow": "finite proof target",
    "needsDefinitions": "needs definitions",
    "analyticHeavy": "analysis-heavy",
    "computationalOnly": "computational",
    "externallyCited": "external citation",
    "compatibilityCondition": "compatibility condition",
    "researchProgram": "research program",
}


def uncomment(text):
    return re.sub(r"(?<!\\)%[^\n]*", "", text)


def manuscript_sources(book):
    seen = set()

    def visit(path):
        if path in seen:
            return
        seen.add(path)
        text = uncomment(path.read_text())
        yield path, text
        for name in re.findall(r"\\input\{([^}]+)\}", text):
            child = book / (name if name.endswith(".tex") else name + ".tex")
            if child.exists():
                yield from visit(child)

    yield from visit(book / "main.tex")


def manuscript_inventory(book):
    inventory = {}
    for path, text in manuscript_sources(book):
        for match in re.finditer(
            r"\\begin\{(theorem|lemma|proposition)\}(?:\[[^\]]*\])?(.*?)\\end\{\1\}",
            text, re.S,
        ):
            label = re.search(r"\\label\{([^}]+)\}", match[2])
            if label is None:
                raise ValueError(f"Unlabeled {match[1]} in {path.relative_to(book)}")
            key = label[1]
            if key in inventory:
                raise ValueError(f"Duplicate manuscript statement label: {key}")
            inventory[key] = (str(path.relative_to(book)), match[1])
    return inventory


def validate_inventory(entries, inventory):
    mapped = {}
    for entry in entries:
        if entry["category"] != "numbered":
            continue
        key = entry["label"]
        if not key or key in mapped:
            raise ValueError(f"Missing or duplicate ledger label: {key!r}")
        mapped[key] = (entry["source"], entry["kind"])
    if inventory != mapped:
        missing = inventory.keys() - mapped.keys()
        extra = mapped.keys() - inventory.keys()
        wrong = {k for k in inventory.keys() & mapped.keys() if inventory[k] != mapped[k]}
        raise ValueError(f"Inventory mismatch: missing={missing}, extra={extra}, wrong source/kind={wrong}")
    return len(inventory)


def tex(text):
    replacements = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
                    "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
                    "^": r"\textasciicircum{}", "<": r"\ensuremath{<}", ">": r"\ensuremath{>}"}
    return "".join(replacements.get(c, c) for c in text)


def title(entry):
    name = entry["title"]
    if re.match(r"^(lem|thm|prop):", name):
        return name.split(":", 1)[1].replace("-", " ")
    return name


def source_title(entry):
    match = re.fullmatch(r"chapters/ch(\d+)/section(\d+)\.tex", entry["source"])
    return f"{match[1]}.{match[2]}" if match else "App. B"


def artifacts(entries):
    numbered = [e for e in entries if e["category"] == "numbered"]
    counts = Counter(e["status"] for e in numbered)
    rows = [r"% Generated by scripts/check_lean_coverage.py --write; do not edit.",
            r"\begin{tabular}{lr}", r"\hline", r"numbered-statement status & count \\", r"\hline"]
    rows += [f"{tex(label)} & {counts[key]} \\\\" for key, label in STATUS.items() if counts[key]]
    rows += [r"\hline", f"total & {len(numbered)} \\\\", r"\hline", r"\end{tabular}", ""]
    table = [r"% Generated by scripts/check_lean_coverage.py --write; do not edit.",
             r"\small", r"\begin{longtable}{>{\raggedright\arraybackslash}p{0.09\textwidth}>{\raggedright\arraybackslash}p{0.65\textwidth}>{\raggedright\arraybackslash}p{0.16\textwidth}}",
             r"\hline", r"source & statement and scope & status \\", r"\hline", r"\endfirsthead",
             r"\hline", r"source & statement and scope & status \\", r"\hline", r"\endhead",
             r"\hline", r"\endfoot"]
    for category, heading in [("numbered", "Numbered statements"), ("identity", "Unnumbered identities"),
                              ("supplement", "Supplementary coverage targets")]:
        table.append(r"\multicolumn{3}{l}{\textbf{" + heading + r"}} \\")
        for entry in entries:
            if entry["category"] != category:
                continue
            cell = tex(title(entry))
            if entry["scope"]:
                cell += r"\newline{\footnotesize " + tex(entry["scope"]) + "}"
            table.append(f"{source_title(entry)} & {cell} & {STATUS[entry['status']]} \\\\")
    table += [r"\end{longtable}", r"\normalsize", ""]
    categories = Counter(e["category"] for e in entries)
    overview = ("% Generated by scripts/check_lean_coverage.py --write; do not edit.\n"
                f"The ledger contains {categories['numbered']} numbered statements, "
                f"{categories['identity']} unnumbered identities, and "
                f"{categories['supplement']} supplementary coverage targets.\n"
                "The counts below refer only to numbered statements.\n")
    md = ["# Current Lean coverage", "", "Generated from the elaborated `BookIndex.lean` ledger.", "",
          "The exported manuscript statement inventory has a unique label for every numbered entry.",
          "Standalone checks validate this snapshot; use `--book PATH` to check current private sources.",
          "Declaration names resolve, and all project theorem dependencies use only the standard Lean axioms.",
          "A complete status applies to the stated scope; it does not certify every surrounding example or discussion.", "",
          "| Numbered-statement status | Count |", "|---|---:|"]
    md += [f"| {label} | {counts[key]} |" for key, label in STATUS.items() if counts[key]]
    md += [f"| Total | {len(numbered)} |", "", "| Source | Category | Statement | Status | Scope |", "|---|---|---|---|---|"]
    for entry in entries:
        md.append(f"| {source_title(entry)} (`{entry['source']}`) | {entry['category']} | {title(entry)} | "
                  f"{STATUS[entry['status']]} | {entry['scope']} |")
    return {
        "chapters/app/lean-ledger-counts.tex": "\n".join(rows),
        "chapters/app/lean-ledger-table.tex": "\n".join(table),
        "chapters/app/lean-ledger-overview.tex": overview,
        "doc/lean-coverage.json": json.dumps(entries, indent=2, ensure_ascii=False) + "\n",
        "doc/lean-coverage-status.md": "\n".join(md) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--book", type=Path, help="private manuscript checkout (optional)")
    parser.add_argument("--write", action="store_true", help="regenerate published artifacts")
    args = parser.parse_args()
    lake = shutil.which("lake") or str(Path.home() / ".elan/bin/lake")
    result = subprocess.run([lake, "env", "lean", "scripts/export_lean_coverage.lean"],
                            cwd=ROOT, capture_output=True, text=True)
    if result.returncode:
        sys.stderr.write(result.stdout + result.stderr)
        return result.returncode
    entries = json.loads(result.stdout.strip().splitlines()[-1])
    inventory_path = ROOT / "lean/manuscript-inventory.json"
    if args.book:
        book = args.book.resolve()
        if not (book / "main.tex").is_file():
            raise ValueError(f"No main.tex in {book}")
        inventory = manuscript_inventory(book)
    else:
        book = None
        inventory = {key: tuple(value) for key, value in
                     json.loads(inventory_path.read_text()).items()}
    count = validate_inventory(entries, inventory)
    generated = artifacts(entries)
    outputs = {
        ROOT / name: content for name, content in generated.items()
        if not name.startswith("chapters/")
    }
    outputs[ROOT / "lean/generated/lean-ledger-counts.tex"] = generated[
        "chapters/app/lean-ledger-counts.tex"]
    outputs[inventory_path] = json.dumps(inventory, indent=2, sort_keys=True) + "\n"
    if book:
        outputs.update({book / name: content for name, content in generated.items()
                        if name.startswith("chapters/")})
    stale = []
    for path, expected in outputs.items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
        elif not path.exists() or path.read_text() != expected:
            stale.append(str(path))
    if stale:
        raise ValueError("Stale generated ledger artifacts; run with --write: " + ", ".join(stale))
    print(f"Coverage checked: {count} numbered statements, {len(entries)} total entries; declarations and axioms verified.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, OSError) as error:
        sys.exit(str(error))
